def table_sigma(levels, m):
    return {
        (i, j, k): tuple(levels[(i + j + k) % m][j])
        for i, j, k in product(range(m), repeat=3)
    }


def test_source_fixture_m5():
    sigma = table_sigma(M5_LEVELS, 5)
    assert len(sigma) == 125
    assert verify_sigma(sigma, 5, 3)
    assert verify_strict_hamiltonian(sigma, 5, 3)


def test_source_fixture_m7():
    sigma = table_sigma(M7_LEVELS, 7)
    assert len(sigma) == 343
    assert verify_sigma(sigma, 7, 3)
    assert verify_strict_hamiltonian(sigma, 7, 3)


def test_source_fixture_m4():
    assert len(M4_SIGMA) == 64
    assert verify_sigma(M4_SIGMA, 4, 3)
    assert verify_strict_hamiltonian(M4_SIGMA, 4, 3)


def test_source_fixture_m4_mutation_rejected():
    sigma = dict(M4_SIGMA)
    original = sigma[(0, 0, 0)]
    alternatives = [(0, 1, 2), (1, 0, 2), (1, 2, 0), (2, 0, 1), (2, 1, 0)]
    sigma[(0, 0, 0)] = next(p for p in alternatives if p != original)
    assert not verify_sigma(sigma, 4, 3)
